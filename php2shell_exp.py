def resolve_redirects(t: HttpTarget, max_hops: int = 3) -> Tuple[HttpTarget, List[str]]:
    """自动跟随 30x（如 http->https、CDN 跳转），返回最终目标与跳转链。"""
    hops: List[str] = []
    cur = t
    for _ in range(max_hops):
        try:
            code, hdrs, _ = cur.request("GET", cur.base_path)
        except Exception:
            break
        loc = hdrs.get("location")
        if code in (301, 302, 307, 308) and loc:
            nxt = urllib.parse.urljoin(cur.url, loc)
            hops.append(nxt)
            cur = HttpTarget(nxt, timeout=cur.timeout, verify_tls=cur.verify_tls)
        else:
            break
    return cur, hops


def check_one(t: HttpTarget) -> Dict:
    code, hdrs, body = t.request("GET", t.base_path)
    blob = (hdrs.get("x-powered-by", "") + " " +
            hdrs.get("server", "") + " " + body[:8192].decode("latin-1", "replace"))
    m = BANNER_RE.search(blob)
    r = {"url": t.url, "http": code, "server": hdrs.get("server"),
         "banner": m.group(0) if m else None, "status": "no_php_version",
         "waf": waf_fingerprint(hdrs, body), "challenge": is_challenge(body)}
    if not m:
        return r
    major, minor, patch = int(m.group(1)), int(m.group(2)), int(m.group(3) or 0)
    key = "%d.%d" % (major, minor)
    if key in FIXED:
        if m.group(3) is None:
            r["status"] = "branch_only"
        elif (major, minor, patch) >= FIXED[key]:
            r["status"] = "patched"
        else:
            r["status"] = "likely_vulnerable"
    else:
        r["status"] = "eol_or_unknown"
    return r


