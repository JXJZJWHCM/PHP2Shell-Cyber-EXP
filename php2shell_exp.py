def probe_paths(t: HttpTarget, paths: Iterable[str], engine: Optional[BypassEngine] = None) -> List[Dict]:
    out = []
    for p in dict.fromkeys(paths):
        engine = engine or BypassEngine(0)
        strategy = engine.next_strategy()
        try:
            code, hdrs, body = t.request("GET", engine.uri(p, strategy),
                                         headers=engine.headers(strategy, "", rand_sid()))
        except Exception as e:
            out.append({"path": p, "score": -1, "err": str(e)})
            continue
        text = body[:4096].decode("latin-1", "replace")
        score = 0
        if code == 200:
            score += 2
        if code in (301, 302, 403):
            score += 1
        if "PHP" in (hdrs.get("x-powered-by", "") + text) or "<?php" in text:
            score += 2
        if re.search(r"session", text, re.I):
            score += 1
        if text.strip() and code == 200:
            score += 1
        if is_challenge(body):
            score -= 2   # 挑战页降权
        out.append({"path": p, "http": code, "len": len(body), "score": score,
                    "classes": CLASS_RE.findall(text)[:8],
                    "challenge": is_challenge(body)})
    return sorted(out, key=lambda d: d["score"], reverse=True)


def build_gadget_matrix(probes: List[Dict], gadget_wordlist: List[str],
                        prop_wordlist: List[str]) -> List[Tuple[str, str]]:
    classes: List[str] = []
    for pr in probes:
        classes += pr.get("classes", [])
    ordered = list(dict.fromkeys(classes + gadget_wordlist))
    return [(g, p) for g in ordered for p in prop_wordlist][:48]


