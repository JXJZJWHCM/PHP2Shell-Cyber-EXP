# 挑战求解器挂钩（滑块/人机层武器化接口）
# ---------------------------------------------------------------------------
# 接口约定：solver_cmd 从环境变量读 TARGET_URL / COOKIES / WAF，
# 求解成功后在 stdout 输出可放行的完整 Cookie 串（如 "acw_tc=...; cdn_sec_tc=..."）。
# 内置 solver_slider_template.py 为无头浏览器/打码服务适配模板。

def solve_challenge(t: HttpTarget, solver_cmd: str, base_cookies: str = "",
                    waf: str = "unknown") -> Dict:
    env = dict(os.environ)
    env.update({"TARGET_URL": t.url, "COOKIES": base_cookies, "WAF": waf})
    try:
        p = subprocess.run(solver_cmd, shell=True, capture_output=True,
                           text=True, timeout=120, env=env)
        out = (p.stdout or "").strip().splitlines()
        cookie = out[-1].strip() if out else ""
        return {"ok": bool(cookie), "cookie": cookie or None,
                "err": (p.stderr or "").strip()[:200]}
    except Exception as e:
        return {"ok": False, "cookie": None, "err": str(e)}


def warmup(t: HttpTarget, engine: BypassEngine) -> Dict:
    """预热：首击采样 WAF 追踪 Cookie（acw_tc/cdn_sec_tc 等）供后续请求复用。"""
    code, hdrs, body = t.request("GET", t.base_path,
                                 headers={"User-Agent": UA_POOL[0]})
    cks = [v.split(";")[0] for k, v in hdrs.items() if k.lower() == "set-cookie"]
    engine.warmed_cookies = cks
    return {"http": code, "cookies": cks, "challenge": is_challenge(body)}


