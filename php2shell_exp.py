class HttpTarget:
    def __init__(self, url: str, timeout: float = 15.0, verify_tls: bool = False):
        u = urllib.parse.urlsplit(url if "://" in url else "http://" + url)
        self.scheme = u.scheme or "http"
        self.host = u.hostname or u.netloc
        self.port = u.port or (443 if self.scheme == "https" else 80)
        self.base_path = u.path or "/"
        self.url = "%s://%s:%s%s" % (self.scheme, self.host, self.port, self.base_path)
        self.timeout = timeout
        self.verify_tls = verify_tls

    def _connect(self) -> socket.socket:
        raw = socket.create_connection((self.host, self.port), timeout=self.timeout)
        if self.scheme == "https":
            ctx = ssl.create_default_context()
            if not self.verify_tls:
                ctx.check_hostname = False
                ctx.verify_mode = ssl.CERT_NONE
            raw = ctx.wrap_socket(raw, server_hostname=self.host)
        return raw

    def request(self, method: str, path: str, body: bytes = b"",
                headers: Optional[Dict[str, str]] = None,
                raw_body_writer=None,
                quirks: Optional[Dict] = None,
                timeout: Optional[float] = None) -> Tuple[int, Dict[str, str], bytes]:
        q = quirks or {}
        hdrs = {"Host": self.host, "User-Agent": "Mozilla/5.0 php2shell-research",
                "Connection": "close", "Accept": "*/*"}
        if headers:
            hdrs.update(headers)
        if body and raw_body_writer is None:
            hdrs["Content-Length"] = str(len(body))
        elif raw_body_writer is not None:
            hdrs.setdefault("Transfer-Encoding", "chunked")
        if q.get("lower_headers"):
            hdrs = {k.lower(): v for k, v in hdrs.items()}
        ver = q.get("http_version", "1.1")
        target = path
        if q.get("abs_uri"):
            target = "%s://%s%s" % (self.scheme, self.host, path)
        req = "%s %s HTTP/%s\r\n" % (method, target, ver) + \
              "".join("%s: %s\r\n" % (k, v) for k, v in hdrs.items()) + "\r\n"
        s = self._connect()
        try:
            s.sendall(req.encode("latin-1"))
            if body and raw_body_writer is None:
                s.sendall(body)
            if raw_body_writer is not None:
                raw_body_writer(s)
            buf = b""
            s.settimeout(timeout or self.timeout)
            while True:
                try:
                    chunk = s.recv(65536)
                except socket.timeout:
                    break
                if not chunk:
                    break
                buf += chunk
            return self._parse_response(buf)
        finally:
            s.close()

    @staticmethod
    def _parse_response(raw: bytes) -> Tuple[int, Dict[str, str], bytes]:
        if not raw:
            return 0, {}, b""
        # 跳过 1xx 中间响应（如 Expect:100-continue 的 100 Continue）
        while re.match(rb"HTTP/\d\.\d\s+1\d\d", raw):
            raw = raw.split(b"\r\n\r\n", 1)[-1]
        head, _, body = raw.partition(b"\r\n\r\n")
        lines = head.decode("latin-1", "replace").split("\r\n")
        m = re.match(r"HTTP/\d\.\d\s+(\d+)", lines[0] if lines else "")
        code = int(m.group(1)) if m else 0
        hdrs = {}
        for line in lines[1:]:
            if ":" in line:
                k, v = line.split(":", 1)
                hdrs[k.strip().lower()] = v.strip()
        return code, hdrs, body


