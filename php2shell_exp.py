# 防御体系精准识别（分层判定：云WAF/人机验证/安全策略/本地WAF/语义识别）
# ---------------------------------------------------------------------------
SEMANTIC_PAYLOADS = [
    "' OR 1=1 -- -", "<script>alert(1)</script>", "{{7*7}}",
    "../../../etc/passwd", ";id;", "eval(base64_decode('YQ=='))",
]

def defense_audit(t: HttpTarget) -> Dict:
    """6 类探针分层判定目标防御体系，输出 layers + 综合画像。"""
    layers: List[Dict] = []
    evidence: Dict = {}

    def probe(method, path, body=b"", ctype=None):
        h = {"User-Agent": UA_POOL[0]}
        if ctype:
            h["Content-Type"] = ctype
        return t.request(method, path, body=body, headers=h)

    # L1 边缘/云 WAF 指纹（支持多层堆叠识别）
    code, hdrs, body = probe("GET", t.base_path)
    stack = waf_stack_fingerprint(hdrs, body)
    waf = stack[0] if stack else "unknown"
    evidence["baseline"] = {"http": code, "server": hdrs.get("server"),
                            "via": hdrs.get("via"), "waf": waf, "waf_stack": stack}
    for w in stack:
        layers.append({"layer": "cloud_waf" if w in
                       ("aliyun_waf", "tencent_waf", "huawei_waf", "cloudflare",
                        "akamai", "aws_waf", "incapsula") else "local_waf",
                       "name": w, "confidence": 0.9, "evidence": "header/body 指纹"})
    if len(stack) >= 2:
        layers.append({"layer": "waf_stacked", "name": "+".join(stack),
                       "confidence": 0.95,
                       "evidence": "多层 WAF 堆叠：%d 层" % len(stack)})
    if any(k in hdrs for k in ("x-tengine-error", "x-cache", "via", "x-cdn")):
        layers.append({"layer": "cdn_edge", "name": hdrs.get("server", "?"),
                       "confidence": 0.7, "evidence": "CDN/边缘头"})

    # L2 人机验证层
    if is_challenge(body):
        layers.append({"layer": "human_challenge", "name": "slider/captcha",
                       "confidence": 0.95,
                       "evidence": "挑战页标记(captcha/slider/token)"})

    # L3 安全策略层（HTTP 方法封禁 / 状态码策略）
    code_u, _, _ = probe("POST", t.base_path, b"a=1",
                         "application/x-www-form-urlencoded")
    code_m, _, _ = probe("POST", t.base_path,
                         b"--X\r\nContent-Disposition: form-data; name=\"a\"\r\n\r\n1\r\n--X--\r\n",
                         "multipart/form-data; boundary=X")
    evidence["post_probe"] = {"urlencoded": code_u, "multipart": code_m}
    if code_u in (403, 405, 406, 501, 520, 521, 522, 523, 524) or \
            code_m in (403, 405, 406, 501, 520, 521, 522, 523, 524):
        layers.append({"layer": "method_policy", "name": "POST-block",
                       "confidence": 0.9,
                       "evidence": "urlencoded=%s multipart=%s" % (code_u, code_m)})

    # L4 语义识别层（攻击特征串 vs 干净串对比）
    block, clean = 0, 0
    for p in SEMANTIC_PAYLOADS:
        try:
            c, _, rb = probe("POST", t.base_path,
                             urllib.parse.urlencode({"q": p}).encode(),
                             "application/x-www-form-urlencoded")
            if c in (403, 406, 419, 429, 520) or is_challenge(rb):
                block += 1
        except Exception:
            block += 1
    try:
        c, _, rb = probe("POST", t.base_path, b"q=hello+world",
                         "application/x-www-form-urlencoded")
        clean = 0 if (c in (403, 406, 419, 429, 520) or is_challenge(rb)) else 1
    except Exception:
        pass
    evidence["semantic"] = {"attack_payloads_blocked": block,
                            "clean_allowed": bool(clean)}
    if block >= 3 and clean:
        layers.append({"layer": "semantic", "name": "payload-scoring",
                       "confidence": 0.8,
                       "evidence": "攻击串 %d/%d 拦截且干净串放行" % (block, len(SEMANTIC_PAYLOADS))})

    # L5 频率限制层（短突发）
    t0 = time.time()
    codes = []
    for _ in range(6):
        try:
            codes.append(probe("GET", t.base_path)[0])
        except Exception:
            codes.append(0)
    if sum(1 for c in codes if c == 429) >= 2 or \
            sum(1 for c in codes if c in (503, 520)) >= 4:
        layers.append({"layer": "rate_limit", "name": "burst-control",
                       "confidence": 0.7, "evidence": "6 连发状态码 %s" % codes})
    evidence["burst"] = {"codes": codes, "secs": round(time.time() - t0, 1)}

    # L6 体积规则探测（两点定界：~1.5KB vs ~3KB，实测目标阈值约 2KB）
    def size_probe(n: int) -> int:
        body = (b"--XYZ\r\nContent-Disposition: form-data; name=\"q\"\r\n\r\n"
                + b"C" * n + b"\r\n--XYZ--\r\n")
        return probe("POST", t.base_path, body,
                     "multipart/form-data; boundary=XYZ")[0]
    try:
        small_c, big_c = size_probe(1500), size_probe(3000)
        evidence["size_probe"] = {"1500B": small_c, "3000B": big_c}
        if big_c in (403, 406, 413, 419, 520) and small_c not in (403, 406, 413, 419, 520):
            layers.append({"layer": "size_limit", "name": "body-size-policy",
                           "confidence": 0.9,
                           "evidence": "1500B=%s 3000B=%s（阈值~2KB）" % (small_c, big_c)})
    except Exception as e:
        evidence["size_probe"] = {"error": str(e)}

    profile = ("aliyun_waf" if any(l.get("name") == "aliyun_waf" for l in layers)
               else next((l["name"] for l in layers if l["layer"] in
                          ("cloud_waf", "local_waf")), "unknown"))
    return {"layers": layers, "evidence": evidence,
            "profile": profile, "depth": len(layers)}


